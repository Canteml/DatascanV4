class IntComMsg;

// -- Qt includes
#include <QObject>
#include <qqml.h>

#include "../prot/ProtMsg.h"

class QThread;
class QMutex;
class QTimer;
class QIODevice;
class ComLinkSerial;
class ComLinkTcpCli;
class ComLinkUdpCli;
class ComLinkTcpConfig;
class ComLinkUdpConfig;
